// The service overview dashboard (001/FR-026): requests, jobs and outbound calls of the api and
// worker. Queue depth is `max by (job_name)` because both services report it (contracts/
// telemetry.md#metrics); counters are zero-initialised (research R18), so `increase` counts the
// first event.

import { dashboard, promName, promSeries, row, stat, timeseries, type Dashboard } from "./build.ts";

const RATE = "$__rate_interval";
const RANGE = "$__range";

const httpCount = promSeries("riviera.http.server.duration", "count");
const httpBucket = promSeries("riviera.http.server.duration", "bucket");
const jobRuns = promName("riviera.jobs.runs");
const jobFailures = promName("riviera.jobs.failures");
const jobBucket = promSeries("riviera.jobs.duration", "bucket");
const queueDepth = promName("riviera.queue.depth");
const externalCalls = promName("riviera.external.calls");
const externalBucket = promSeries("riviera.external.duration", "bucket");

function quantile(q: number, bucket: string, by: string): string {
  return `histogram_quantile(${String(q)}, sum by (${by}, le) (rate(${bucket}[${RATE}])))`;
}

export const OVERVIEW_FILE = "service/overview.json";

export function overviewDashboard(): Dashboard {
  return dashboard({
    uid: "service-overview",
    title: "Service overview",
    description:
      "Requests per route, background jobs and Common Ground / Discogs calls of riviera-api and riviera-worker. Generated by packages/telemetry/src/dashboards (make dashboards); do not edit in Grafana.",
    tags: ["riviera", "service"],
    panels: [
      row("Requests"),
      timeseries(
        "Request rate by route",
        "Requests per second, health endpoints excluded.",
        "reqps",
        [{ expr: `sum by (route) (rate(${httpCount}[${RATE}]))`, legend: "{{route}}" }],
      ),
      timeseries(
        "Errors by route",
        "Server errors (5xx) and client errors (4xx) per second. Unknown paths are one `unmatched` route.",
        "reqps",
        [
          {
            expr: `sum by (route) (rate(${httpCount}{status_class="5xx"}[${RATE}]))`,
            legend: "{{route}} 5xx",
          },
          {
            expr: `sum by (route) (rate(${httpCount}{status_class="4xx"}[${RATE}]))`,
            legend: "{{route}} 4xx",
          },
        ],
      ),
      timeseries("Latency by route", "Request duration, p50 and p95.", "s", [
        { expr: quantile(0.5, httpBucket, "route"), legend: "{{route}} p50" },
        { expr: quantile(0.95, httpBucket, "route"), legend: "{{route}} p95" },
      ]),
      stat("Requests in range", "Requests per route over the selected time range.", "short", [
        { expr: `sum by (route) (increase(${httpCount}[${RANGE}]))`, legend: "{{route}}" },
      ]),

      row("Jobs"),
      timeseries("Job runs by outcome", "Job attempts per second.", "ops", [
        {
          expr: `sum by (job_name, outcome) (rate(${jobRuns}[${RATE}]))`,
          legend: "{{job_name}} {{outcome}}",
        },
      ]),
      timeseries(
        "Queue depth",
        "Queued jobs; both api and worker report it, so the panel takes the max.",
        "short",
        [{ expr: `max by (job_name) (${queueDepth})`, legend: "{{job_name}}" }],
      ),
      stat(
        "Job failures in range",
        "Failed attempts over the selected time range; each failed attempt counts once.",
        "short",
        [
          {
            expr: `sum by (job_name) (increase(${jobFailures}[${RANGE}]))`,
            legend: "{{job_name}}",
          },
        ],
      ),
      timeseries("Job duration", "Job attempt duration, p95.", "s", [
        { expr: quantile(0.95, jobBucket, "job_name"), legend: "{{job_name}} p95" },
      ]),

      row("Common Ground and Discogs"),
      timeseries(
        "Calls by outcome",
        "Outbound calls per second; `rate_limited` (429) is separate from `failed`.",
        "ops",
        [
          {
            expr: `sum by (service, outcome) (rate(${externalCalls}[${RATE}]))`,
            legend: "{{service}} {{outcome}}",
          },
        ],
      ),
      timeseries("Call latency", "Outbound call duration, p95.", "s", [
        {
          expr: quantile(0.95, externalBucket, "service, operation"),
          legend: "{{service}} {{operation}} p95",
        },
      ]),
    ],
  });
}
